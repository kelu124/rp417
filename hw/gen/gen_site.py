#!/usr/bin/python3
"""Regenerate the GitHub Pages material in docs/ from the board.

Run from the repo root after any board, schematic or BOM change:
    /usr/bin/python3 hw/gen/gen_site.py

Writes:
  docs/images/rp417-v1.0-*.png   renders (copied from hw/renders/), copper layer plots, assembly views
  docs/pinmap.md                 every CH32H417 / RP2354B pin and the RP<->CH32 links (from the netlist)
  docs/bom.md                    assembly BOM table (from hw/production/bom.csv)
Needs kicad-cli and inkscape. Render the 3D views first (see hw/README.md).
"""
import csv, os, re, shutil, subprocess, tempfile, collections

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HW = os.path.join(ROOT, "hw")
DOCS = os.path.join(ROOT, "docs")
IMG = os.path.join(DOCS, "images")
PCB = os.path.join(HW, "rp417.kicad_pcb")
SCH = os.path.join(HW, "rp417.kicad_sch")
TAG = "rp417-v1.0"
os.makedirs(IMG, exist_ok=True)


def run(*a):
    subprocess.run(a, check=True, capture_output=True)


# ------------------------------------------------------------------ images
for src, dst in (("top", "top"), ("bottom", "bottom"), ("angled", "top-angled"), ("angled-back", "bottom-angled")):
    shutil.copy(os.path.join(HW, "renders", f"rp417-{src}.png"), os.path.join(IMG, f"{TAG}-{dst}.png"))

PLOTS = [  # name, layers, mirror
    ("F_Cu", "F.Cu", False), ("In1_Cu", "In1.Cu", False), ("In2_Cu", "In2.Cu", False),
    ("In3_Cu", "In3.Cu", False), ("In4_Cu", "In4.Cu", False), ("B_Cu", "B.Cu", True),
    ("assembly-top", "F.Silkscreen,F.Fab", False), ("assembly-bottom", "B.Silkscreen,B.Fab", True),
]
with tempfile.TemporaryDirectory() as tmp:
    for name, layers, mirror in PLOTS:
        svg = os.path.join(tmp, f"{name}.svg")
        cmd = ["kicad-cli", "pcb", "export", "svg", "--mode-single", "-o", svg, "-l", layers,
               "--cl", "Edge.Cuts", "--page-size-mode", "2", "--exclude-drawing-sheet", "--drill-shape-opt", "2"]
        if mirror:
            cmd.append("--mirror")
        run(*cmd, PCB)
        run("inkscape", svg, "--export-type=png", f"--export-filename={os.path.join(IMG, f'{TAG}-{name}.png')}",
            "--export-width=1400", "--export-background=white", "--export-background-opacity=1")
        print("plot", name)

# ------------------------------------------------------------------ netlist
with tempfile.TemporaryDirectory() as tmp:
    net = os.path.join(tmp, "n.net")
    run("kicad-cli", "sch", "export", "netlist", "--format", "kicadsexpr", "-o", net, SCH)
    t = re.sub(r"\s+", " ", open(net).read())
values = dict(re.findall(r'\(comp \(ref "([^"]+)"\) \(value "([^"]*)"\)', t))
pins = collections.defaultdict(dict)          # ref -> pin -> (function, net)
for m in re.finditer(r'\(net \(code "\d+"\) \(name "([^"]*)"\)(.*?)\)\s*\)(?= \(net |\s*\)\s*\)\s*$)', t):
    name, body = m.groups()
    for n in re.finditer(r'\(node \(ref "([^"]+)"\) \(pin "([^"]+)"\)(?: \(pinfunction "([^"]*)"\))?', body):
        ref, pin, fn = n.groups()
        fn = re.sub(rf"_{re.escape(pin)}$", "", fn or "")   # KiCad appends _<pin> to duplicated names
        pins[ref][pin] = (fn, name)
net_members = collections.defaultdict(list)
for ref, pp in pins.items():
    for pin, (_, n) in pp.items():
        net_members[n].append((ref, pin))


def clean(n):
    return "—" if n.startswith("unconnected-") else f"`{n.lstrip('/')}`"


def pinkey(p):
    return int(p) if p.isdigit() else 999


# RP <-> CH32 links: U2 net -> (direct or through a 2-pin R/C) -> U1 net
links = []
for pin, (fn, n) in sorted(pins["U2"].items(), key=lambda x: pinkey(x[0])):
    if n.startswith("unconnected-") or n in ("GND", "+3V3", "+1V1"):
        continue
    for ref, rp in net_members[n]:
        if ref == "U1":
            links.append((fn, n, "direct", rp, pins["U1"][rp][0], n))
        elif ref[0] in "R" and len(pins[ref]) == 2:
            other = [v for k, v in pins[ref].items() if k != rp][0][1]
            for r2, p2 in net_members[other]:
                if r2 == "U1" and not re.match(r"^(GND|\+\d|VDD)", other):   # skip dividers / pull-downs to rails
                    links.append((fn, n, f"{ref} {values[ref]}", p2, pins["U1"][p2][0], other))
# switched paths (capture switch, USB switch) are documented in prose
L = ["# Pin map — RP2354B ↔ CH32H417MEU6", "",
     "Generated by `hw/gen/gen_site.py` from the schematic netlist (`hw/gen/build.py` is the source of truth).",
     "Pin numbers are package pins: CH32H417MEU6 QFN88 (U1), RP2354B QFN80 (U2). Design rationale: "
     "[architecture](architecture.md); decisions are referenced as Dxx.", "",
     "## 1. Direct RP2354B ↔ CH32 links", "",
     "Every line between the two chips has a series resistor (back-feed limit when the CH32 domain is off, D29).",
     "Not listed here: the DVP capture bus and PCLK (through the 2:1 switches U11–U13, D55) and the CH32 debug",
     "pins PB8/PB9 (through the USB switch U4, D26) — see [architecture](architecture.md).", "",
     "| RP2354B pin | RP net | Series part | CH32 pin | CH32 function | CH32 net |", "|---|---|---|---|---|---|"]
for fn, n, via, cp, cfn, cn in links:
    rp_pin = [p for p, v in pins["U2"].items() if v[1] == n][0]
    L.append(f"| {rp_pin} {fn} | {clean(n)} | {via} | {cp} | {cfn} | {clean(cn)} |")
for title, ref in (("2. CH32H417MEU6 (U1, QFN88) — all pins", "U1"), ("3. RP2354B (U2, QFN80) — all pins", "U2")):
    L += ["", f"## {title}", "", "| Pin | Function | Net |", "|---|---|---|"]
    for p, (fn, n) in sorted(pins[ref].items(), key=lambda x: pinkey(x[0])):
        L.append(f"| {p} | {fn.replace('/', ' / ')} | {clean(n)} |")
open(os.path.join(DOCS, "pinmap.md"), "w").write("\n".join(L) + "\n")
print("pinmap.md", len(links), "links")

# ------------------------------------------------------------------ BOM page
rows = list(csv.DictReader(open(os.path.join(HW, "production", "bom.csv"), encoding="utf-8-sig")))
B = ["# Bill of materials (JLCPCB assembly)", "",
     "Generated by `hw/gen/gen_site.py` from [`hw/production/bom.csv`](https://github.com/kelu124/rp417/blob/main/hw/production/bom.csv).",
     f"**{len(rows)} lines, {sum(int(r['Quantity']) for r in rows)} parts**, every line with an LCSC number (D68).",
     "LCSC numbers live in `hw/gen/build.py` (`LCSC_STD` for standard passives, `lcsc=` on each IC) and are copied",
     "into the `LCSC` / `MPN` fields of every symbol and footprint.", "",
     "- **Consigned:** U1 CH32H417MEU6 — not stocked by JLCPCB, supplied by the user (D43, D58).",
     "- **Not fitted (DNP):** U10 ADC10065 (hand-soldered by the user, D42); the 2.54 mm headers J5, J6, J7 (D68).",
     "- **Not parts:** mounting holes H1–H4, solder jumper JP1.",
     "- Passives are JLC *basic* parts where one exists (no feeder fee); a few are *preferred* or *extended*.",
     "  Check stock on the JLCPCB site when ordering.", "",
     "| Designators | Qty | Value | Footprint | LCSC |", "|---|---|---|---|---|"]
for r in sorted(rows, key=lambda r: (r["Designator"][0], -int(r["Quantity"]))):
    lc = r["LCSC Part #"].strip()
    link = f"[{lc}](https://www.lcsc.com/product-detail/{lc}.html)" if lc else ""
    B.append(f"| {r['Designator']} | {r['Quantity']} | {r['Value']} | {r['Footprint']} | {link} |")
open(os.path.join(DOCS, "bom.md"), "w").write("\n".join(B) + "\n")
print("bom.md", len(rows), "lines")
